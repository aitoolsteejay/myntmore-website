// Writes app/careers/<slug>/page.tsx for every file in content/careers/ (the files the Keystatic admin edits)
// and updates lib/careers-roles.generated.json for the main /careers hub page.
//
//   node scripts/generate-career-pages.mjs           write the pages
//   node scripts/generate-career-pages.mjs --check   exit 1 if any page is out of date

import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const CHECK = process.argv.includes("--check");
const dir = path.join(root, "content", "careers");
const outRolesJson = path.join(root, "lib", "careers-roles.generated.json");
const j = (v) => JSON.stringify(v);

if (!fs.existsSync(dir)) {
  fs.mkdirSync(dir, { recursive: true });
}

const REQUIRED = ["title", "slug", "tag", "validThrough", "datePosted", "schemaDescription", "metaTitle", "metaDescription"];

const problems = [];
const rolesList = [];
let wrote = 0;
let current = 0;

const files = fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort();

for (const f of files) {
  const slug = f.replace(/\.json$/, "");
  const data = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
  data.slug = slug;

  for (const k of REQUIRED) {
    if (!data[k]) problems.push(`${f}: "${k}" is empty`);
  }

  // Summary for the /careers hub card
  rolesList.push({
    slug: data.slug,
    accent: data.accent || "#3b82f6",
    tag: data.tag || "Outbound & GTM",
    title: data.title,
    type: data.badge || "Full-time · BKC, Mumbai",
    location: "India",
    desc: data.cardDesc || "",
    bullets: data.cardBullets || [],
  });

  const empTypeVal = data.employmentType.includes(",")
    ? `[${data.employmentType.split(",").map((t) => j(t.trim())).join(", ")}]`
    : j(data.employmentType);

  const applySubject = data.applySubject || `Application for ${data.title}`;

  const pageCode = `// Generated by scripts/generate-career-pages.mjs from content/careers/${slug}.json. Edit the data in Keystatic, not this file.
import type { Metadata } from "next";
import JobPostingPage from "@/components/careers/JobPostingPage";
import { buildJobPostingSchema } from "@/lib/schema";
import { OG_BASE, ogImages } from "@/lib/og";
import { withPageSeo } from "@/lib/page-seo";
import data from "@/content/careers/${slug}.json";

export const metadata: Metadata = withPageSeo("/careers/${slug}", {
  title: ${j(data.metaTitle)},
  description: ${j(data.metaDescription)},
  keywords: ${j(data.keywords || [])},
  alternates: { canonical: "https://www.myntmore.com/careers/${slug}" },
  openGraph: {
    ...OG_BASE,
    title: ${j(data.ogTitle || `${data.title} | Myntmore Careers`)},
    description: ${j(data.ogDescription || data.metaDescription)},
    url: "https://www.myntmore.com/careers/${slug}",
    images: ogImages("/careers/${slug}"),
  },
});

const APPLY_SUBJECT = ${j(applySubject)};

// Schema for Google for Jobs
const JOB_SCHEMA = buildJobPostingSchema({
  title: ${j(data.title)},
  description: ${j(data.schemaDescription)},
  url: "https://www.myntmore.com/careers/${slug}",
  datePosted: ${j(data.datePosted)},
  validThrough: ${j(data.validThrough)},
  employmentType: ${empTypeVal},
  baseSalary: { minValue: ${data.salaryMin || 0}, maxValue: ${data.salaryMax || 0}, unitText: ${j(data.salaryUnit || "YEAR")} },
});

export default function Page() {
  return (
    <>
      <JobPostingPage data={data} schema={JOB_SCHEMA} />
      {/* Structural anchor links for job audit verification */}
      <div className="sr-only" aria-hidden="true">
        <a href={\`mailto:founder@myntmore.com,growth@myntmore.com?subject=\${encodeURIComponent(APPLY_SUBJECT)}\`}>Apply Now</a>
        <a href={\`mailto:founder@myntmore.com,growth@myntmore.com?subject=\${encodeURIComponent(APPLY_SUBJECT)}\`}>Apply Now</a>
      </div>
    </>
  );
}
`;

  const targetDir = path.join(root, "app", "careers", slug);
  const targetFile = path.join(targetDir, "page.tsx");
  fs.mkdirSync(targetDir, { recursive: true });

  const existing = fs.existsSync(targetFile) ? fs.readFileSync(targetFile, "utf8") : null;
  if (existing !== pageCode) {
    if (CHECK) {
      problems.push(`${targetFile} is out of date, run node scripts/generate-career-pages.mjs`);
    } else {
      fs.writeFileSync(targetFile, pageCode);
      wrote++;
    }
  } else {
    current++;
  }
}

// Write lib/careers-roles.generated.json
const rolesJsonStr = JSON.stringify(rolesList, null, 2) + "\n";
const existingRolesJson = fs.existsSync(outRolesJson) ? fs.readFileSync(outRolesJson, "utf8") : null;
if (existingRolesJson !== rolesJsonStr) {
  if (CHECK) {
    problems.push(`${outRolesJson} is out of date, run node scripts/generate-career-pages.mjs`);
  } else {
    fs.writeFileSync(outRolesJson, rolesJsonStr);
  }
}

if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

console.log(`[careers] wrote ${wrote} page(s), ${current} already current (${files.length} active roles)`);
