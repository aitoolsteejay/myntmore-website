// Writes app/case-studies/<slug>/page.tsx for every file in content/case-study-long/ (the files the Keystatic
// admin edits, one "Long-form case study" entry each). The long-form case studies each have their own layout, so
// the page body lives in components/case-studies/long/<slug>.tsx and reads its copy from the same JSON. The page
// itself is thin on purpose, like the other generated pages: literal metadata, so the sitemap, llms-full, keyword
// and site-audit tooling that read page files see a real title, description and keywords.
//
// The case studies that use components/case-studies/CaseStudyLayout live in content/case-study-pages/ and are
// built by generate-case-study-detail-pages.mjs. The 50 library case studies come from lib/case-study-library.json.
//
//   node scripts/generate-case-study-long-pages.mjs           write the pages
//   node scripts/generate-case-study-long-pages.mjs --check   exit 1 if any page is out of date
//
// A page also needs its line in app/sitemap.ts and its card on the /case-studies listing; neither is edited here.
// The generator warns when the sitemap line is missing.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const CHECK = process.argv.includes("--check");
const dir = path.join(root, "content/case-study-long");
const j = JSON.stringify;

const REQUIRED = ["metaTitle", "metaDescription", "ogTitle", "ogDescription", "schemaHeadline", "schemaDescription", "datePublished", "dateModified"];

const page = (d) => `// Generated by scripts/generate-case-study-long-pages.mjs from content/case-study-long/${d.slug}.json. Edit the data, not this file.
import type { Metadata } from "next";
import { OG_BASE } from "@/lib/og";
import Body from "@/components/case-studies/long/${d.slug}";

export const metadata: Metadata = {
  title: ${j(d.metaTitle)},
  description: ${j(d.metaDescription)},
  keywords: [${d.keywords.map((k) => j(k)).join(", ")}],
  alternates: { canonical: "https://www.myntmore.com/case-studies/${d.slug}" },
  openGraph: {
    ...OG_BASE,
    title: ${j(d.ogTitle)},
    description: ${j(d.ogDescription)},
    url: "https://www.myntmore.com/case-studies/${d.slug}",
    images: [{ url: "/og-image.png", width: 1200, height: 630, alt: "Myntmore" }],
  },
};

export default function Page() {
  return <Body />;
}
`;

const problems = [];
const sitemap = fs.readFileSync(path.join(root, "app/sitemap.ts"), "utf8");
let wrote = 0, current = 0;
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const slug = f.replace(/\.json$/, "");
  const d = { ...JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")), slug };
  for (const k of REQUIRED) if (!d[k]) problems.push(`${f}: "${k}" is empty`);
  if (!Array.isArray(d.keywords)) problems.push(`${f}: "keywords" must be a list`);
  if (!fs.existsSync(path.join(root, "components/case-studies/long", `${slug}.tsx`))) problems.push(`${f}: components/case-studies/long/${slug}.tsx is missing`);
  if (d.metaTitle && d.metaTitle.length + " | Myntmore".length > 60) console.warn(`[case-study-long] warning: ${f}: search title is ${d.metaTitle.length + 11} characters with the site suffix, over 60 (Google may cut it)`);
  if (!sitemap.includes(`/case-studies/${slug}\``)) console.warn(`[case-study-long] warning: /case-studies/${slug} is not listed in app/sitemap.ts`);
  const file = path.join(root, "app/case-studies", slug, "page.tsx");
  const next = page(d);
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (prev === next) current++;
  else if (CHECK) problems.push(`${path.relative(root, file)} is out of date`);
  else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, next); wrote++; }
}
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
console.log(CHECK ? `[case-study-long] ok (${current} pages)` : `[case-study-long] wrote ${wrote} page(s), ${current} already current`);
