// Builds the guides written in the content admin ("New guides", content/resource-guides/*.json):
//   - app/resources/guides/<slug>/page.tsx   one thin page per guide: literal metadata (so the sitemap, llms-full and
//     site-audit tooling that read page files see real text) and a call to <GuidePage />, which renders it
//   - lib/guide-index.generated.json         the cards the /resources/guides page adds to its list
//   - the guide entries in app/sitemap.ts    between two marker comments
// The 19 older guides under app/resources/guides keep their own hand-built pages; a new guide whose address
// matches one of those is refused so it can never overwrite one.
//
//   node scripts/generate-guide-pages.mjs           write everything
//   node scripts/generate-guide-pages.mjs --check   exit 1 if anything is out of date
import fs from "node:fs";
import path from "node:path";
import { checkEntry } from "./lib/content-rules.mjs";

const root = process.cwd();
const CHECK = process.argv.includes("--check");
const dir = path.join(root, "content/resource-guides");
const guidesDir = path.join(root, "app/resources/guides");
const j = (v) => JSON.stringify(v);
const MARK = /^\/\/ Generated by scripts\/generate-guide-pages/;

const iso = (date) => `${date}T09:00:00+05:30`;

const page = (d) => `// Generated by scripts/generate-guide-pages.mjs from content/resource-guides/${d.slug}.json. Edit the data, not this file.
import type { Metadata } from "next";
import { OG_BASE, ogImages } from "@/lib/og";
import GuidePage from "@/components/guides/GuidePage";
import { buildArticleSchema, SITE_URL } from "@/lib/schema";

const SLUG = ${j(d.slug)};
const PAGE_URL = \`\${SITE_URL}/resources/guides/\${SLUG}\`;
const TITLE = ${j(d.title)};
const META_DESCRIPTION = ${j(d.metaDescription)};

export const metadata: Metadata = {
  title: ${j(d.metaTitle)},
  description: META_DESCRIPTION,
  alternates: { canonical: PAGE_URL },
  keywords: ${j(d.keywords ?? [])},
  openGraph: {
    ...OG_BASE,
    title: ${j(d.ogTitle || `${d.metaTitle} | Myntmore`)},
    description: ${j(d.ogDescription || d.metaDescription)},
    url: PAGE_URL,
    images: ogImages("/resources/guides/${d.slug}"),
  },
};

const SECTIONS = ${j(d.sections.map((s) => ({ heading: s.heading, ...(s.paragraphs?.length ? { paragraphs: s.paragraphs } : {}), ...(s.steps?.length ? { steps: s.steps } : {}), ...(s.copyBlocks?.length ? { copyBlocks: s.copyBlocks } : {}), ...(s.table?.rows?.length ? { table: s.table } : {}) })), null, 2)};
${
  d.faqs?.length
    ? `
const FAQS = ${j(d.faqs, null, 2)};
`
    : ""
}
const SCHEMA = buildArticleSchema({
  headline: TITLE,
  description: META_DESCRIPTION,
  url: PAGE_URL,
  datePublished: ${j(iso(d.datePublished))},
  dateModified: ${j(iso(d.dateModified || d.datePublished))},
});

export default function Page() {
  return (
    <GuidePage
      slug={SLUG}
      title={TITLE}
      tag={${j(d.tag)}}
      accent={${j(d.accent)}}
      readTime={${d.readTime}}
      intro={${j(d.intro)}}
      sections={SECTIONS}${d.faqs?.length ? "\n      faqs={FAQS}" : ""}${d.relatedLinks?.length ? `\n      relatedLinks={${j(d.relatedLinks)}}` : ""}${d.ctaHeading ? `\n      cta={${j({ heading: d.ctaHeading, text: d.ctaText, label: d.ctaButtonLabel, href: d.ctaButtonHref })}}` : ""}
      articleSchema={SCHEMA}
    />
  );
}
`;

const problems = [];
const guides = [];
fs.mkdirSync(dir, { recursive: true });
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const slug = f.replace(/\.json$/, "");
  const d = { ...JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")), slug };
  // Build rules shared with the content admin: scripts/lib/content-rules.mjs
  for (const p of await checkEntry("resourceGuides", d, null)) problems.push(`${f}: ${p.message}`);
  // Never overwrite one of the hand-built guides.
  const target = path.join(guidesDir, slug, "page.tsx");
  if (fs.existsSync(target) && !MARK.test(fs.readFileSync(target, "utf8"))) problems.push(`${f}: /resources/guides/${slug} is already a hand-built guide; choose a different guide address`);
  guides.push(d);
}
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

let stale = 0, wrote = 0;
const writeIf = (file, next) => {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (prev === next) return;
  stale++;
  if (!CHECK) { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, next); wrote++; }
  else console.error(`${path.relative(root, file)} is out of date`);
};

for (const d of guides) writeIf(path.join(guidesDir, d.slug, "page.tsx"), page(d));

// Newest first on the guides page.
const cards = guides
  .slice()
  .sort((a, b) => b.datePublished.localeCompare(a.datePublished) || a.slug.localeCompare(b.slug))
  .map((d) => ({ href: `/resources/guides/${d.slug}`, tag: d.tag, title: d.title, excerpt: d.excerpt, readTime: `${d.readTime} min read`, accent: d.accent }));
writeIf(path.join(root, "lib/guide-index.generated.json"), JSON.stringify(cards, null, 2) + "\n");

const START = "    // BEGIN generated: new guides (scripts/generate-guide-pages.mjs)";
const END = "    // END generated: new guides";
const sitemapFile = path.join(root, "app/sitemap.ts");
const sm = fs.readFileSync(sitemapFile, "utf8");
const a = sm.indexOf(START), b = sm.indexOf(END);
if (a < 0 || b < 0) { console.error(`app/sitemap.ts is missing the markers:\n${START}\n${END}`); process.exit(1); }
const entries = guides.map((d) => `    { url: \`\${base}/resources/guides/${d.slug}\`, lastModified: lastMod("/resources/guides/${d.slug}"), changeFrequency: "monthly", priority: 0.7 },`);
writeIf(sitemapFile, sm.slice(0, a) + [START, ...entries, END].join("\n") + sm.slice(b + END.length));

// Generated pages whose JSON file is gone are reported, not deleted.
for (const name of fs.readdirSync(guidesDir)) {
  const p = path.join(guidesDir, name, "page.tsx");
  if (fs.existsSync(p) && MARK.test(fs.readFileSync(p, "utf8")) && !guides.some((g) => g.slug === name)) {
    console.warn(`[guides] warning: app/resources/guides/${name} has no content/resource-guides/${name}.json any more; delete the folder if the guide was removed on purpose`);
  }
}

if (CHECK) {
  if (stale) process.exit(1);
  console.log(`[guides] ok (${guides.length} new guides)`);
} else console.log(`[guides] wrote ${wrote} file(s), ${guides.length} new guides`);
