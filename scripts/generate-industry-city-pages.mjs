// Writes app/b2b-lead-generation-<slug>/page.tsx for every file in content/industry-city-pages/
// (the files the Keystatic admin edits), updates lib/industry-city-pages.generated.json, and keeps
// the generated block in app/sitemap.ts in sync.
//
//   node scripts/generate-industry-city-pages.mjs           write the pages
//   node scripts/generate-industry-city-pages.mjs --check   exit 1 if any file is out of date
import fs from "node:fs";
import path from "node:path";
import { checkEntry } from "./lib/content-rules.mjs";
import { fsContext } from "./lib/fs-context.mjs";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const CHECK = process.argv.includes("--check");
const dir = path.join(root, "content/industry-city-pages");
const j = (v) => JSON.stringify(v);


const page = (d) => `// Generated by scripts/generate-industry-city-pages.mjs from content/industry-city-pages/${d.slug}.json. Edit the data, not this file.
import type { Metadata } from "next";
import { OG_BASE, ogImages } from "@/lib/og";
import IndustryCityPage from "@/components/industry-city/IndustryCityPage";
import data from "@/content/industry-city-pages/${d.slug}.json";

export const metadata: Metadata = {
  title: ${j(d.metaTitle)},
  description: ${j(d.metaDescription)},
  alternates: { canonical: "https://www.myntmore.com/b2b-lead-generation-${d.slug}" },
  keywords: ${j(d.keywords)},
  openGraph: {
    ...OG_BASE,
    title: ${j(d.ogTitle)},
    description: ${j(d.ogDescription)},
    url: "https://www.myntmore.com/b2b-lead-generation-${d.slug}",
    images: ogImages("/b2b-lead-generation-${d.slug}"),
  },
};

export default function Page() {
  return <IndustryCityPage data={data} />;
}
`;

const problems = [];
const pages = [];
const ctx = fsContext(root);

if (fs.existsSync(dir)) {
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
    const slug = f.replace(/\.json$/, "");
    const raw = fs.readFileSync(path.join(dir, f), "utf8");
    const d = { ...JSON.parse(raw), slug };
    // Build rules shared with the content admin: scripts/lib/content-rules.mjs
    for (const p of await checkEntry("industryCityPages", d, ctx)) problems.push(`${f}: ${p.message}`);
    if (d.metaTitle && d.metaTitle.length + " | Myntmore".length > 60) {
      console.warn(
        `[industry-city] warning: ${f}: search title is ${d.metaTitle.length + 11} chars with suffix (over 60)`
      );
    }
    pages.push(d);
  }
}

if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

let stale = 0;
let wrote = 0;
const writeIf = (file, next) => {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (prev === next) return;
  stale++;
  if (!CHECK) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, next);
    wrote++;
  } else {
    console.error(`${path.relative(root, file)} is out of date`);
  }
};

for (const d of pages) {
  writeIf(path.join(root, "app", `b2b-lead-generation-${d.slug}`, "page.tsx"), page(d));
}

// Write lightweight index JSON for CityPage, IndustryCityPage cross-links, HTML sitemap, and OG card lookup.
const index = pages.map((d) => ({
  slug: d.slug,
  href: `/b2b-lead-generation-${d.slug}`,
  citySlug: d.citySlug,
  cityName: d.cityName,
  industrySlug: d.industrySlug,
  industryName: d.industryName,
  badge: d.badge,
  emoji: d.emoji,
  h1: d.h1,
  metaDescription: d.metaDescription,
}));
writeIf(path.join(root, "lib/industry-city-pages.generated.json"), JSON.stringify(index, null, 2) + "\n");

// Keep sitemap entries in app/sitemap.ts in sync between marker comments.
const START = "    // BEGIN generated: industry city pages (scripts/generate-industry-city-pages.mjs)";
const END = "    // END generated: industry city pages";
const sitemapFile = path.join(root, "app/sitemap.ts");
const sm = fs.readFileSync(sitemapFile, "utf8");
const a = sm.indexOf(START);
const b = sm.indexOf(END);
if (a < 0 || b < 0) {
  console.error(`app/sitemap.ts is missing the markers:\n${START}\n${END}`);
  process.exit(1);
}
const entries = pages.map(
  (d) =>
    `    { url: \`\${base}/b2b-lead-generation-${d.slug}\`, lastModified: lastMod("/b2b-lead-generation-${d.slug}"), changeFrequency: "monthly", priority: 0.6 },`
);
writeIf(sitemapFile, sm.slice(0, a) + [START, ...entries, END].join("\n") + sm.slice(b + END.length));

if (CHECK) {
  if (stale) process.exit(1);
  console.log(`[industry-city] ok (${pages.length} pages)`);
} else {
  console.log(`[industry-city] wrote ${wrote} file(s), ${pages.length} pages`);
}
