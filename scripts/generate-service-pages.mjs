// Writes app/services/<slug>/page.tsx for every file in content/service-pages/ (the files the
// Keystatic admin edits). The pages are thin on purpose, like the landing, city and case study
// pages: literal metadata, so the sitemap, llms-full, keyword and site-audit tooling that read
// page files see a real title, description and keywords, and a call to the page's component,
// which reads the rest of its copy from the same JSON file.
//
//   node scripts/generate-service-pages.mjs           write the pages
//   node scripts/generate-service-pages.mjs --check   exit 1 if any page is out of date
//
// Each page's component is hand-written (the layouts differ). Add a new service by writing its
// component, adding its slug to COMPONENTS below, and creating content/service-pages/<slug>.json.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const CHECK = process.argv.includes("--check");
const dir = path.join(root, "content/service-pages");

// slug -> [component import path, default-export name used in the page]
const COMPONENTS = {
  "account-based-marketing": ["./AccountBasedMarketingClient", "AccountBasedMarketingClient", "AccountBasedMarketingPage"],
  "ai-lead-generation": ["./AiLeadGenerationClient", "AiLeadGenerationClient", "AiLeadGenerationPage"],
  "gtm-strategy": ["./GtmStrategyClient", "GtmStrategyClient", "GtmStrategyPage"],
  "personal-branding": ["./PersonalBrandingClient", "PersonalBrandingClient", "PersonalBrandingPage"],
  "sales-intelligence": ["./SalesIntelligenceClient", "SalesIntelligenceClient", "SalesIntelligencePage"],
  "do-it-yourself": ["./DoItYourselfClient", "DoItYourselfClient", "DoItYourselfPage"],
  "cold-email": ["@/components/cold-emailing/ColdEmailingPackage", "ColdEmailingPackage", "ColdEmailPage"],
  "linkedin-outreach": ["@/components/linkedin-outreach/LinkedinOutreachPage", "LinkedinOutreach", "LinkedinOutreachPage"],
};
const j = JSON.stringify;

const page = (d) => {
  const [from, Component, fn] = COMPONENTS[d.slug];
  return `// Generated by scripts/generate-service-pages.mjs from content/service-pages/${d.slug}.json. Edit the data, not this file.
import type { Metadata } from "next";
import ${Component} from ${j(from)};

export const metadata: Metadata = {
  title: ${j(d.metaTitle)},
  description: ${j(d.metaDescription)},
  keywords: [${d.keywords.map((k) => j(k)).join(", ")}],
  alternates: { canonical: "https://www.myntmore.com/services/${d.slug}" },
  openGraph: {
    title: ${j(d.ogTitle)},
    description: ${j(d.ogDescription)},
    url: "https://www.myntmore.com/services/${d.slug}",
    images: [{ url: "/og-image.png", width: 1200, height: 630, alt: "Myntmore" }],
  },
};

export default function ${fn}() {
  return <${Component} />;
}
`;
};

const problems = [];
let wrote = 0, current = 0;
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const slug = f.replace(/\.json$/, "");
  const d = { ...JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")), slug };
  if (!COMPONENTS[slug]) { problems.push(`${f}: no component registered for "${slug}" in scripts/generate-service-pages.mjs`); continue; }
  if (d.metaTitle && d.metaTitle.length + " | Myntmore".length > 60) problems.push(`${f}: search title is ${d.metaTitle.length + 11} characters with the site suffix, over 60`);
  if (d.metaDescription && d.metaDescription.length > 160) problems.push(`${f}: search description is ${d.metaDescription.length} characters, over 160`);
  const file = path.join(root, "app/services", slug, "page.tsx");
  const next = page(d);
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (prev === next) current++;
  else if (CHECK) problems.push(`${path.relative(root, file)} is out of date`);
  else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, next); wrote++; }
}
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
console.log(CHECK ? `[service-pages] ok (${current} pages)` : `[service-pages] wrote ${wrote} page(s), ${current} already current`);
