// Writes app/calendar/<slug>/page.tsx for every file in content/calendar-pages/
// (the files the Keystatic admin edits).
//
//   node scripts/generate-calendar-pages.mjs           write the pages
//   node scripts/generate-calendar-pages.mjs --check   exit 1 if any page is out of date

import fs from "node:fs";
import path from "node:path";
import { checkEntry } from "./lib/content-rules.mjs";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const CHECK = process.argv.includes("--check");
const dir = path.join(root, "content", "calendar-pages");
const j = (v) => JSON.stringify(v);

if (!fs.existsSync(dir)) {
  fs.mkdirSync(dir, { recursive: true });
}

function pascalCase(s) {
  return s
    .split(/[-_]+/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");
}

const problems = [];
let wrote = 0;
let current = 0;

const files = fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort();

for (const f of files) {
  const slug = f.replace(/\.json$/, "");
  const data = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
  data.slug = slug;

  for (const p of await checkEntry("calendarPages", data, null)) {
    problems.push(`${f}: ${p.message}`);
  }

  const canon = data.canonicalPath || `/calendar/${slug}`;
  const isEnwil = data.client === "enwil";
  const compName = isEnwil ? "EnwilCalendarClient" : "CalendarPageClient";

  const content = `// Generated by scripts/generate-calendar-pages.mjs from content/calendar-pages/${f}.
// Do not edit this file directly; edit the JSON in the admin or on disk.
import type { Metadata } from "next";
import ${compName} from "@/components/calendar/${compName}";
import { OG_BASE, ogImages } from "@/lib/og";
import { withPageSeo } from "@/lib/page-seo";

export const metadata: Metadata = withPageSeo(${j(canon)}, {
  title: ${j(data.metaTitle)},
  description: ${j(data.metaDescription)},
  robots: { index: false, follow: false },
  alternates: { canonical: "https://www.myntmore.com" + ${j(canon)} },
  openGraph: {
    ...OG_BASE,
    title: ${j(data.metaTitle)},
    description: ${j(data.metaDescription)},
    url: "https://www.myntmore.com" + ${j(canon)},
    images: ogImages(${j(canon)}),
  },
});

export default function Calendar${pascalCase(slug)}Page() {
  return (
    <${compName}
      canonicalPath=${j(canon)}
      ${isEnwil ? `embedUrl=${j(data.embedUrl)}` : `dataUrl=${j(data.embedUrl)}`}
      badge=${j(data.badge)}
      title=${j(data.heading)}
      description=${j(data.description)}
      ${!isEnwil ? `duration=${j(data.duration || "30 Mins")}` : ""}
    />
  );
}
`;

  const pageDir = path.join(root, "app", "calendar", slug);
  const out = path.join(pageDir, "page.tsx");
  if (!fs.existsSync(pageDir)) fs.mkdirSync(pageDir, { recursive: true });

  const existing = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : null;
  if (existing !== content) {
    if (CHECK) {
      console.error(`app/calendar/${slug}/page.tsx is out of date. Run npm run calendar:build`);
      process.exit(1);
    }
    fs.writeFileSync(out, content);
    wrote++;
  } else {
    current++;
  }
}

if (problems.length) {
  console.error(`Calendar pages: ${problems.length} problem(s):\n  ${problems.join("\n  ")}`);
  process.exit(1);
}

console.log(
  CHECK
    ? `Calendar pages: ${files.length} up to date`
    : `Calendar pages: ${wrote} written, ${current} up to date`,
);
