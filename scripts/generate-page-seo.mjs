// Builds lib/page-seo.generated.json from content/page-seo/*.json (the "Page search titles"
// collection in the Keystatic admin). lib/page-seo.ts reads it through withPageSeo().
// Also warns about hand-written pages that are not connected to the admin yet.
//
//   node scripts/generate-page-seo.mjs           write lib/page-seo.generated.json
//   node scripts/generate-page-seo.mjs --check   exit 1 if it is stale
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "content/page-seo");
const out = path.join(root, "lib/page-seo.generated.json");

// Pages whose search title is edited elsewhere in the admin, or that visitors never see.
const NOT_HERE = new Map([
  ["app/resources/blogs/[slug]/page.tsx", "blog posts have their own search fields"],
  ["app/agency-vs-in-house/page.tsx", "redirected in next.config.js"],
  ["app/founder-meeting/page.tsx", "redirected in next.config.js"],
]);

const entries = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const e = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
  const where = `content/page-seo/${f}`;
  if (typeof e.path !== "string" || !e.path.startsWith("/")) throw new Error(`${where}: "path" must start with /`);
  if (!e.title?.trim()) throw new Error(`${where}: "title" is empty`);
  if (!e.description?.trim()) throw new Error(`${where}: "description" is empty`);
  if (entries[e.path]) throw new Error(`${where}: a second entry for ${e.path}`);
  entries[e.path] = { title: e.title.trim(), description: e.description.trim() };
}
const sorted = Object.fromEntries(Object.keys(entries).sort().map((k) => [k, entries[k]]));
const next = JSON.stringify(sorted, null, 1) + "\n";

// Every hand-written page should call withPageSeo (in the page or its layout).
function pages(d) {
  return fs.readdirSync(d, { withFileTypes: true }).flatMap((x) => {
    const p = path.join(d, x.name);
    if (x.isDirectory()) return x.name === "keystatic" || x.name === "api" ? [] : pages(p);
    return x.name === "page.tsx" ? [p] : [];
  });
}
const unconnected = [];
for (const p of pages(path.join(root, "app"))) {
  const rel = path.relative(root, p);
  const src = fs.readFileSync(p, "utf8");
  if (NOT_HERE.has(rel) || /^\/\/ Generated by /.test(src)) continue;
  const layout = path.join(path.dirname(p), "layout.tsx");
  const layoutSrc = fs.existsSync(layout) ? fs.readFileSync(layout, "utf8") : "";
  if (!src.includes("withPageSeo(") && !layoutSrc.includes("withPageSeo(")) unconnected.push(rel);
}
for (const rel of unconnected) {
  console.warn(`[page-seo] warning: ${rel} has no search title in the admin; add an entry under content/page-seo/ and wrap its metadata in withPageSeo()`);
}

if (process.argv.includes("--check")) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (current !== next) {
    console.error("[page-seo] lib/page-seo.generated.json is stale, run npm run page-seo:build");
    process.exit(1);
  }
  console.log(`[page-seo] ok (${Object.keys(sorted).length} pages)`);
} else {
  fs.writeFileSync(out, next);
  console.log(`[page-seo] wrote ${Object.keys(sorted).length} pages`);
}
