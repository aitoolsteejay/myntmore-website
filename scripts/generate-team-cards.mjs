// Writes app/<slug>/page.tsx for every visiting card in content/team-cards/
// (the files the Keystatic admin edits).
//
//   node scripts/generate-team-cards.mjs           write the pages
//   node scripts/generate-team-cards.mjs --check   exit 1 if any page is out of date

import fs from "node:fs";
import path from "node:path";
import { checkEntry } from "./lib/content-rules.mjs";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const CHECK = process.argv.includes("--check");
const dir = path.join(root, "content", "team-cards");
const j = (v) => JSON.stringify(v);

if (!fs.existsSync(dir)) {
  fs.mkdirSync(dir, { recursive: true });
}

function pascalCase(s) {
  return s
    .split(/[-_]+/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");
}

const problems = [];
let wrote = 0;
let current = 0;

const files = fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort();

for (const f of files) {
  const slug = f.replace(/\.json$/, "");
  const data = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
  data.slug = slug;

  for (const p of await checkEntry("teamCards", data, null)) {
    problems.push(`${f}: ${p.message}`);
  }

  const canon = `/${slug}`;
  const compName = `${pascalCase(slug)}Card`;

  // Build contacts array
  const contacts = [];
  if (data.whatsappUrl) {
    contacts.push(`{ label: "WhatsApp", cta: "Reach out on WhatsApp", href: ${j(data.whatsappUrl)}, icon: <WhatsAppIcon />, bg: "#25D366" }`);
  }
  if (data.linkedinUrl) {
    contacts.push(`{ label: "LinkedIn", cta: "Connect on LinkedIn", href: ${j(data.linkedinUrl)}, icon: <LinkedInIcon />, bg: "#0A66C2" }`);
  }
  if (data.instagramUrl) {
    contacts.push(`{ label: "Instagram", cta: "Follow on Instagram", href: ${j(data.instagramUrl)}, icon: <InstagramIcon />, bg: "#C13584" }`);
  }
  if (data.phone) {
    contacts.push(`{ label: "Call", cta: "Call", href: ${j(`tel:${data.phone}`)}, icon: <PhoneIcon />, bg: "#F5B731" }`);
  }
  if (data.email) {
    contacts.push(`{ label: "Email", cta: "Email", href: ${j(`mailto:${data.email}`)}, icon: <EmailIcon />, bg: "#0A66C2" }`);
  }
  if (data.newsletterUrl) {
    contacts.push(`{ label: "Newsletter", cta: "Subscribe to the Myntmore newsletter", href: ${j(data.newsletterUrl)}, icon: <NewsletterIcon />, bg: "#D97706" }`);
  }

  const sameAsList = [];
  if (data.linkedinUrl) sameAsList.push(data.linkedinUrl);
  if (data.instagramUrl) sameAsList.push(data.instagramUrl);

  const extraImports = [];
  if (data.includeSignature || data.includeQuiz) {
    const parts = [];
    if (data.includeQuiz) parts.push("OutboundQuiz");
    if (data.includeSignature) parts.push("SignatureMark");
    extraImports.push(`import { ${parts.join(", ")} } from "./CardDetails";`);
  }

  const content = `// Generated by scripts/generate-team-cards.mjs from content/team-cards/${f}.
// Do not edit this file directly; edit the JSON in the admin or on disk.
import type { Metadata } from "next";
${extraImports.length ? extraImports.join("\n") + "\n" : ""}import VisitingCard from "@/app/components/VisitingCard";
import JsonLd from "@/app/components/JsonLd";
import { WhatsAppIcon, LinkedInIcon, InstagramIcon, EmailIcon, PhoneIcon, NewsletterIcon } from "@/app/components/ContactIcons";
import { SITE_URL } from "@/lib/schema";
import { OG_BASE, ogImages } from "@/lib/og";
import { withPageSeo } from "@/lib/page-seo";

export const metadata: Metadata = withPageSeo(${j(canon)}, {
  title: ${j(data.metaTitle)},
  description: ${j(data.metaDescription)},
  alternates: { canonical: \`\${SITE_URL}${canon}\` },
  robots: { index: false, follow: false },
  openGraph: {
    ...OG_BASE,
    title: ${j(data.ogTitle || `${data.fullName} | ${data.jobTitle}, Myntmore`)},
    description: ${j(data.metaDescription)},
    url: \`\${SITE_URL}${canon}\`,
    images: ogImages(${j(canon)}),
  },
});

const PERSON_SCHEMA = {
  "@context": "https://schema.org",
  "@type": "Person",
  name: ${j(data.fullName)},
  jobTitle: ${j(data.jobTitle || "Outbound Specialist")},
  worksFor: { "@type": "Organization", name: "Myntmore", url: SITE_URL, logo: \`\${SITE_URL}/logo.png\` },
  url: \`\${SITE_URL}${canon}\`,
  ${data.email ? `email: ${j(data.email)},\n  ` : ""}${data.phone ? `telephone: ${j(data.phone)},\n  ` : ""}sameAs: ${j(sameAsList)},
};

export default function ${compName}() {
  return (
    <>
      <JsonLd data={PERSON_SCHEMA} />
      <VisitingCard
        path=${j(canon)}
        name=${j(data.fullName)}
        title=${j(data.role)}
        ${data.includeSignature ? `nameDecoration={<SignatureMark />}\n        ` : ""}${data.intro ? `intro=${j(data.intro)}\n        ` : ""}${data.ctaHref ? `ctaHref=${j(data.ctaHref)}\n        ` : ""}${data.ctaLabel ? `ctaLabel=${j(data.ctaLabel)}\n        ` : ""}photoSrc=${j(data.photoSrc)}
        photoAlt=${j(data.photoAlt)}
        vCardHref=${j(data.vCardHref)}
        contacts={[
          ${contacts.join(",\n          ")}
        ]}
      >${data.includeQuiz ? `\n        <OutboundQuiz />\n      ` : ""}</VisitingCard>
    </>
  );
}
`;

  const pageDir = path.join(root, "app", slug);
  const out = path.join(pageDir, "page.tsx");
  if (!fs.existsSync(pageDir)) fs.mkdirSync(pageDir, { recursive: true });

  const existing = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : null;
  if (existing !== content) {
    if (CHECK) {
      console.error(`app/${slug}/page.tsx is out of date. Run npm run team-cards:build`);
      process.exit(1);
    }
    fs.writeFileSync(out, content);
    wrote++;
  } else {
    current++;
  }
}

if (problems.length) {
  console.error(`Team cards: ${problems.length} problem(s):\n  ${problems.join("\n  ")}`);
  process.exit(1);
}

console.log(
  CHECK
    ? `Team cards: ${files.length} up to date`
    : `Team cards: ${wrote} written, ${current} up to date`,
);
