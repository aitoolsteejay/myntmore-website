// Builds the events from content/events/*.json (the files the Keystatic admin edits as "Events"):
//   - lib/events.generated.json      the list the /events page, the event pop-up and UpcomingEvents read
//                                     (through lib/events-data.ts), with the dates and times worked out
//   - app/events/<slug>/page.tsx      a thin page with literal metadata and <EventPage slug="..." />
//   - the event entries in app/sitemap.ts         between two marker comments
// So a new event needs no code change. All times are India time (IST).
//
//   node scripts/generate-event-pages.mjs           write everything
//   node scripts/generate-event-pages.mjs --check   exit 1 if anything is out of date
import fs from "node:fs";
import path from "node:path";
import { checkEntry } from "./lib/content-rules.mjs";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const CHECK = process.argv.includes("--check");
const dir = path.join(root, "content/events");
const out = path.join(root, "lib/events.generated.json");
const j = JSON.stringify;

const MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];

// "13:00" -> "1:00 PM"
const clock = (hm) => {
  const [h, m] = hm.split(":").map(Number);
  return `${h % 12 === 0 ? 12 : h % 12}:${String(m).padStart(2, "0")} ${h < 12 ? "AM" : "PM"}`;
};

const problems = [];
const events = [];
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const slug = f.replace(/\.json$/, "");
  const raw = fs.readFileSync(path.join(dir, f), "utf8");
  const d = JSON.parse(raw);
  // Build rules shared with the content admin: scripts/lib/content-rules.mjs
  const found = await checkEntry("events", { ...d, slug }, null);
  for (const p of found) problems.push(`${f}: ${p.message}`);
  if (found.length) continue;

  const [y, mo, da] = d.date.split("-").map(Number);
  const month = MONTHS[mo - 1];
  const longDate = `${month} ${da}, ${y}`;
  events.push({
    slug,
    tag: d.tag,
    title: d.title,
    description: d.cardDescription,
    longDescription: d.description,
    isoDate: d.date,
    isoStartDateTime: `${d.date}T${d.startTime}:00+05:30`,
    isoEndDateTime: `${d.date}T${d.endTime}:00+05:30`,
    displayDate: `${month.slice(0, 3)} ${da}, ${y}`,
    longDate,
    time: `${clock(d.startTime)} – ${clock(d.endTime)} IST`,
    format: d.format,
    accent: d.accent,
    breadcrumbLabel: d.breadcrumbLabel,
    topics: d.topics ?? [],
    registrationUrl: d.registrationUrl || "",
    recordingUrl: d.recordingUrl || "",
    showPopup: Boolean(d.showPopup),
    metaTitle: d.metaTitle,
    metaDescription: d.metaDescription,
    keywords: d.keywords ?? [],
    ogTitle: d.ogTitle || `${d.metaTitle} | Myntmore`,
    ogDescription: d.ogDescription || d.metaDescription,
  });
}
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}
// Soonest first, so "the next event" is always the first upcoming one.
events.sort((a, b) => a.isoStartDateTime.localeCompare(b.isoStartDateTime));

const page = (e) => `// Generated by scripts/generate-event-pages.mjs from content/events/${e.slug}.json. Edit the data, not this file.
import type { Metadata } from "next";
import { OG_BASE, ogImages } from "@/lib/og";
import EventPage from "@/components/events/EventPage";

const URL = "https://www.myntmore.com/events/${e.slug}";

export const metadata: Metadata = {
  title: ${j(e.metaTitle)},
  description: ${j(e.metaDescription)},${e.keywords.length ? `\n  keywords: ${j(e.keywords)},` : ""}
  alternates: { canonical: URL },
  openGraph: {
    ...OG_BASE,
    title: ${j(e.ogTitle)},
    description: ${j(e.ogDescription)},
    url: URL,
    images: ogImages("/events/${e.slug}"),
  },
};

// The page switches from "register" to "recording" when the event ends, so it is re-rendered at most hourly.
export const revalidate = 3600;

export default function Page() {
  return <EventPage slug=${j(e.slug)} />;
}
`;

let wrote = 0, current = 0;
const write = (file, next) => {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (prev === next) current++;
  else if (CHECK) problems.push(`${path.relative(root, file)} is out of date`);
  else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, next); wrote++; }
};
// Keywords only go into each page's metadata, not into the index the site reads.
write(out, JSON.stringify(events.map(({ keywords, ...rest }) => rest), null, 2) + "\n");
for (const e of events) write(path.join(root, "app/events", e.slug, "page.tsx"), page(e));

const START = "    // BEGIN generated: events (scripts/generate-event-pages.mjs)";
const END = "    // END generated: events";
const sitemapFile = path.join(root, "app/sitemap.ts");
const sm = fs.readFileSync(sitemapFile, "utf8");
const a = sm.indexOf(START), b = sm.indexOf(END);
if (a < 0 || b < 0) { console.error(`app/sitemap.ts is missing the markers:\n${START}\n${END}`); process.exit(1); }
const entries = events.map((e) => `    { url: \`\${base}/events/${e.slug}\`, lastModified: lastMod("/events/${e.slug}"), changeFrequency: "monthly", priority: 0.7 },`);
write(sitemapFile, sm.slice(0, a) + [START, ...entries, END].join("\n") + sm.slice(b + END.length));

// Event folders under app/events that no longer have a JSON file are reported, not deleted.
for (const name of fs.readdirSync(path.join(root, "app/events"))) {
  const p = path.join(root, "app/events", name, "page.tsx");
  if (fs.existsSync(p) && /^\/\/ Generated by scripts\/generate-event-pages/.test(fs.readFileSync(p, "utf8")) && !events.some((e) => e.slug === name)) {
    console.warn(`[events] warning: app/events/${name} has no content/events/${name}.json any more; delete the folder if the event was removed on purpose`);
  }
}
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
console.log(CHECK ? `[events] ok (${events.length} events)` : `[events] wrote ${wrote} file(s), ${current} already current (${events.length} events)`);
